#!/usr/bin/env node
/**
 * Repository code-size and function-arity guard.
 *
 * Why: small modules and narrow call signatures keep the WorkRecord Core boundaries
 * reviewable; generated evidence is checked at its maintainable source instead.
 */
import {
  readFileSync,
  readdirSync,
} from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  findArityViolations,
  findAstDocumentationViolations,
  findComplexityViolations,
  findSyntaxViolations,
  isAstFile,
  MAX_FUNCTION_ARGS,
  MAX_FUNCTION_COMPLEXITY,
} from "./code-quality-ast.mjs";
import { isProtectedRepositoryPath } from "./protected-paths.mjs";

export {
  extractModuleScripts,
  findArityViolations,
  findComplexityViolations,
  findSyntaxViolations,
  MAX_FUNCTION_ARGS,
  MAX_FUNCTION_COMPLEXITY,
} from "./code-quality-ast.mjs";

/** Maximum physical lines permitted in one maintainable code file. */
export const MAX_FILE_LINES = 500;

/** Minimum normalized consecutive lines required for a reported clone block. */
export const MIN_DUPLICATE_BLOCK_LINES = 12;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CODE_EXTENSIONS = new Set([
  ".cjs",
  ".css",
  ".cts",
  ".html",
  ".js",
  ".jsx",
  ".mjs",
  ".mts",
  ".sh",
  ".ts",
  ".tsx",
]);
const EXCLUDED_DIRECTORIES = new Set([
  ".agents",
  ".codacy",
  ".codegraph",
  ".codex",
  ".git",
  ".next",
  "build",
  "coverage",
  "dist",
  "fixtures",
  "node_modules",
]);
const EXCLUDED_PREFIXES = ["deploy/secrets/", "docs/images/"];

/** Explicit generated-file exceptions with their required rationale. */
export const FILE_EXEMPTIONS = new Map([
  [
    "mvei/apps/schema-site/index.html",
    "generated byte-identically from src/content.mjs and covered by site.test.mjs",
  ],
  [
    "mvei/apps/workbench/src/index.html",
    "generated byte-identically from src/shell.mjs and covered by shell.test.mjs",
  ],
]);

/** Count logical physical lines, including a final unterminated line. */
export function countPhysicalLines(source) {
  if (!source) return 0;
  const breaks = source.match(/\n/g)?.length ?? 0;
  return breaks + (source.endsWith("\n") ? 0 : 1);
}

function textFileHasModuleComment(source, filePath) {
  const extension = extname(filePath);
  if (extension === ".html") {
    return /^\s*(?:<!doctype[^>]*>\s*)?<!--[\s\S]*?-->/i.test(source);
  }
  if (extension === ".css") return /^\s*\/\*/.test(source);
  if (extension === ".sh") {
    return /^(?:#![^\n]*\n)?\s*#(?!!)/.test(source);
  }
  return true;
}

/** Find source-header and exported declaration JSDoc violations in one code file. */
export function findDocumentationViolations(source, filePath = "source.ts") {
  if (!isAstFile(filePath)) {
    return {
      module: textFileHasModuleComment(source, filePath)
        ? []
        : [{ filePath, line: 1, kind: "module" }],
      exports: [],
    };
  }
  return findAstDocumentationViolations(source, filePath);
}

/** Group byte-identical maintainable source files so copies cannot silently drift. */
export function findExactDuplicateGroups(sources) {
  const pathsBySource = new Map();
  for (const { filePath, source } of sources) {
    const paths = pathsBySource.get(source) ?? [];
    paths.push(filePath);
    pathsBySource.set(source, paths);
  }
  return [...pathsBySource.values()]
    .filter((paths) => paths.length > 1)
    .map((paths) => [...paths].sort())
    .sort((left, right) => left[0].localeCompare(right[0]));
}

function cloneLines(source) {
  return source
    .split(/\r?\n/u)
    .map((line, index) => ({
      line: line.trim().replace(/\s+/gu, " "),
      sourceLine: index + 1,
    }))
    .filter(({ line }) => line && !/^(?:\/\/|\/\*|\*|#(?!!))/u.test(line));
}

function cloneWindows(filePath, source) {
  const lines = cloneLines(source);
  const windows = [];
  for (let start = 0; start <= lines.length - MIN_DUPLICATE_BLOCK_LINES; start += 1) {
    const block = lines.slice(start, start + MIN_DUPLICATE_BLOCK_LINES);
    windows.push({ filePath, start, block: block.map(({ line }) => line).join("\n") });
  }
  return { lines, windows };
}

/**
 * Find maximal whitespace-normalized clone blocks across separate maintained files.
 * Why: byte-identical file checks miss copied implementations that have drifted elsewhere.
 */
function collectCloneIndexes(sources) {
  const windowsByBlock = new Map();
  const linesByFile = new Map();
  for (const { filePath, source } of sources) {
    const { lines, windows } = cloneWindows(filePath, source);
    linesByFile.set(filePath, lines);
    for (const window of windows) {
      const matches = windowsByBlock.get(window.block) ?? [];
      matches.push(window);
      windowsByBlock.set(window.block, matches);
    }
  }
  return { linesByFile, windowsByBlock };
}

function crossFileMatches(matches) {
  const unique = matches.filter(
    (match, index) =>
      matches.findIndex(
        (other) => other.filePath === match.filePath && other.start === match.start,
      ) === index,
  );
  return new Set(unique.map((match) => match.filePath)).size > 1 ? unique : [];
}

function hasClonePredecessor(matches, linesByFile, windowsByBlock) {
  const first = matches[0];
  if (first.start === 0) return false;
  const priorBlock = (linesByFile.get(first.filePath) ?? [])
    .slice(first.start - 1, first.start - 1 + MIN_DUPLICATE_BLOCK_LINES)
    .map(({ line }) => line)
    .join("\n");
  const previous = windowsByBlock.get(priorBlock) ?? [];
  return matches.every((match) =>
    previous.some(
      (candidate) =>
        candidate.filePath === match.filePath &&
        candidate.start === match.start - 1,
    ),
  );
}

function cloneLength(matches, linesByFile) {
  let length = MIN_DUPLICATE_BLOCK_LINES;
  const reference = linesByFile.get(matches[0].filePath) ?? [];
  while (
    reference[matches[0].start + length] !== undefined &&
    matches.every((match) => {
      const lines = linesByFile.get(match.filePath) ?? [];
      return lines[match.start + length]?.line === reference[matches[0].start + length]?.line;
    })
  ) length += 1;
  return length;
}

function cloneLocations(matches, linesByFile) {
  const length = cloneLength(matches, linesByFile);
  return matches
    .map((match) => {
      const lines = linesByFile.get(match.filePath) ?? [];
      return `${match.filePath}:${lines[match.start]?.sourceLine}-${lines[match.start + length - 1]?.sourceLine}`;
    })
    .sort();
}

/** Find maximal whitespace-normalized clone blocks across maintained source files. */
export function findCloneBlockGroups(sources) {
  const { linesByFile, windowsByBlock } = collectCloneIndexes(sources);
  const groups = [];
  for (const matches of windowsByBlock.values()) {
    const unique = crossFileMatches(matches);
    if (unique.length === 0 || hasClonePredecessor(unique, linesByFile, windowsByBlock)) continue;
    groups.push(cloneLocations(unique, linesByFile));
  }
  return groups.sort((left, right) => left[0].localeCompare(right[0]));
}

function normalizedRelativePath(base, absolutePath) {
  return relative(base, absolutePath).split(sep).join("/");
}

function excludedPath(relPath) {
  return EXCLUDED_PREFIXES.some((prefix) => relPath.startsWith(prefix));
}

function collectCodeFiles(base, directory = base, files = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolutePath = join(directory, entry.name);
    const relPath = normalizedRelativePath(base, absolutePath);
    if (isProtectedRepositoryPath(relPath)) continue;
    if (entry.isDirectory()) {
      if (EXCLUDED_DIRECTORIES.has(entry.name) || excludedPath(`${relPath}/`)) {
        continue;
      }
      collectCodeFiles(base, absolutePath, files);
      continue;
    }
    if (
      entry.isFile() &&
      CODE_EXTENSIONS.has(extname(entry.name)) &&
      !excludedPath(relPath) &&
      !FILE_EXEMPTIONS.has(relPath)
    ) {
      files.push({ absolutePath, relPath });
    }
  }
  return files;
}

/** Scan maintainable repository code for size and arity violations. */
export function collectQualityViolations(base = root) {
  const files = collectCodeFiles(base);
  const oversized = [];
  const arity = [];
  const complexity = [];
  const syntax = [];
  const moduleDocs = [];
  const exportDocs = [];
  const sources = [];
  for (const file of files) {
    const source = readFileSync(file.absolutePath, "utf8");
    sources.push({ filePath: file.relPath, source });
    const lines = countPhysicalLines(source);
    if (lines > MAX_FILE_LINES) {
      oversized.push({ filePath: file.relPath, lines });
    }
    const documentation = findDocumentationViolations(source, file.relPath);
    moduleDocs.push(...documentation.module);
    exportDocs.push(...documentation.exports);
    if (isAstFile(file.relPath)) {
      syntax.push(...findSyntaxViolations(source, file.relPath));
      arity.push(...findArityViolations(source, file.relPath));
      complexity.push(...findComplexityViolations(source, file.relPath));
    }
  }
  return {
    files,
    oversized,
    arity,
    complexity,
    syntax,
    duplicates: findExactDuplicateGroups(sources),
    cloneBlocks: findCloneBlockGroups(sources),
    moduleDocs,
    exportDocs,
  };
}

const QUALITY_ISSUE_FIELDS = [
  "oversized",
  "arity",
  "complexity",
  "syntax",
  "duplicates",
  "cloneBlocks",
  "moduleDocs",
  "exportDocs",
];

function hasQualityViolations(result) {
  return QUALITY_ISSUE_FIELDS.some((field) => result[field].length > 0);
}

function printQualityViolations(result) {
  const reports = [
    [result.oversized, (issue) => `  - ${issue.filePath}: ${issue.lines} lines (max ${MAX_FILE_LINES})`],
    [result.arity, (issue) => `  - ${issue.filePath}:${issue.line} ${issue.name}: ${issue.args} args (max ${MAX_FUNCTION_ARGS})`],
    [result.syntax, (issue) => `  - ${issue.filePath}:${issue.line} syntax: ${issue.message}`],
    [result.complexity, (issue) => `  - ${issue.filePath}:${issue.line} ${issue.name}: complexity ${issue.complexity} (max ${MAX_FUNCTION_COMPLEXITY})`],
    [result.duplicates, (paths) => `  - exact duplicate source files: ${paths.join(", ")}`],
    [result.cloneBlocks, (paths) => `  - clone block: ${paths.join(", ")}`],
    [result.moduleDocs, (issue) => `  - ${issue.filePath}:${issue.line} missing file-level module comment`],
    [result.exportDocs, (issue) => `  - ${issue.filePath}:${issue.line} ${issue.kind} ${issue.name}: missing JSDoc`],
  ];
  for (const [issues, format] of reports) {
    for (const issue of issues) console.error(format(issue));
  }
}

function main() {
  const result = collectQualityViolations();
  if (hasQualityViolations(result)) {
    console.error("Code quality check FAILED");
    printQualityViolations(result);
    process.exitCode = 1;
    return;
  }
  console.log(
    `OK   code-quality: ${result.files.length} maintainable files; max ${MAX_FILE_LINES} LOC; max ${MAX_FUNCTION_ARGS} args; max complexity ${MAX_FUNCTION_COMPLEXITY}; no exact files or clone blocks`,
  );
  for (const [filePath, reason] of FILE_EXEMPTIONS) {
    console.log(`     generated exception: ${filePath} - ${reason}`);
  }
}

if (
  process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url
) {
  main();
}
